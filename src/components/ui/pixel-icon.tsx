export type PixelIconName = keyof typeof GLYPHS;

type Run = { x: number; y: number; width: number };

function toRuns(rows: readonly string[]): Run[] {
  const runs: Run[] = [];
  rows.forEach((row, y) => {
    let start = -1;
    for (let x = 0; x <= row.length; x += 1) {
      const filled = row[x] === "#";
      if (filled && start < 0) start = x;
      if (!filled && start >= 0) {
        runs.push({ x: start, y, width: x - start });
        start = -1;
      }
    }
  });
  return runs;
}

const RUNS = Object.fromEntries(
  Object.entries(GLYPHS).map(([name, rows]) => [name, toRuns(rows)]),
) as Record<PixelIconName, Run[]>;

const GOAT_RUNS = toRuns(GOAT);

function PixelSvg({
  runs,
  width,
  height,
  className,
  label,
}: {
  runs: Run[];
  width: number;
  height: number;
  className: string;
  label?: string;
}) {
  return (
    <svg
      viewBox={`0 0 ${width} ${height}`}
      className={className}
      shapeRendering="crispEdges"
      fill="currentColor"
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    >
      {runs.map((run) => (
        <rect key={`${run.x}-${run.y}`} x={run.x} y={run.y} width={run.width} height={1} />
      ))}
    </svg>
  );
}

export function PixelIcon({
  name,
  className = "h-5 w-5",
  label,
}: {
  name: PixelIconName;
  className?: string;
  /** Accessible name. Omit for a decorative glyph beside visible text. */
  label?: string;
}) {
  return <PixelSvg runs={RUNS[name]} width={10} height={10} className={className} label={label} />;
}

export function GoatMark({ className = "h-12 w-11", label }: { className?: string; label?: string }) {
  return <PixelSvg runs={GOAT_RUNS} width={12} height={13} className={className} label={label} />;
}
